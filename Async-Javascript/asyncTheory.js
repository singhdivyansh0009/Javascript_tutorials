/*
  => By default the javascript is syncronous and single threaded
  -> Syncronous means that the execution of the code is sequential
     other task is start after the execution of previous task.
  -> Single threaded means only one operation is performed at a time.

  => Blocked and non-blocked Execution :
  -> Blocked execution are the execution in which the execution of code is blocked
     at any operation till the operation is finished.
  -> Non blocked execution are the execution in which the execution of code is continues 
     without waiting for the execution of any operation.    
*/
